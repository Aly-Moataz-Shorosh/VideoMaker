def card(kind, titles, desc, tags, pin=None):
    lines = [f'النوع: {kind}', '', 'العناوين المقترحة:']
    lines += [f'{i}) {t}' for i, t in enumerate(titles, 1)]
    lines += ['', 'الديسكريبشن المقترح:', desc.strip(), '', ' '.join(tags)]
    if pin:
        lines += ['', 'كومنت مثبّت مقترح:', pin]
    return '\n'.join(lines) + '\n'


